    /// <summary>A slider limit's row: its range and step after its description.</summary>
    public static string Row(SliderLimit limit, string description)
    {
        ArgumentNullException.ThrowIfNull(limit);
        return $"| `{limit.Group}.{limit.Name}` | {description} {limit.Min} to {limit.Max}, in steps of {limit.Step}. "
            + $"| `{limit.Default}` |";
    }

    /// <summary>The page for <paramref name="features"/>, with Unix line ends and a final one. A feature in a group
    /// with no section here throws: a new group needs its section written first.</summary>
    public static string Render(SettingCatalogue features)
    {
        ArgumentNullException.ThrowIfNull(features);
        var keys = features.Features.Select(SettingKey.Of).ToList();
        if (keys.FirstOrDefault(key => Sections.All(section => section.Group != key.Group)) is { } lost)
        {
            throw new ArgumentException($"{lost.Path} is in a group with no section on the page", nameof(features));
        }
        var page = new StringBuilder();
        Block(page, Head);
        foreach (var (group, section) in Sections)
        {
            Block(page, section, keys.Where(key => key.Group == group).Select(Row));
        }
        Block(page, SoundsSection, Enum.GetValues<Cue>().Select(cue => Sound(SettingKey.Of(cue))));
        Block(page, LimitsSection, Sliders.Select(slider => Row(slider.Limit, slider.Description)));
        Block(page, Tail);
        return page.ToString().TrimEnd('\n') + "\n";
    }

    /// <summary>A feature's row: a testing feature says so, and is off by default.</summary>
    public static string Row(SettingKey key)
    {
        ArgumentNullException.ThrowIfNull(key);
        return key.Testing
            ? $"| `{key.Name}` | {key.Description} Still being tested. | testing, off |"
            : $"| `{key.Name}` | {key.Description} | `true` |";
    }

    private static string Sound(SettingKey key) =>
        $"| `{key.Name}` | {key.Description} | on, volume {CueSetting.Default.Volume} |";

    private static void Block(StringBuilder page, string text, IEnumerable<string>? rows = null)
    {
        page.Append(text.ReplaceLineEndings("\n")).Append('\n');
        foreach (var row in rows ?? [])
        {
            page.Append(row).Append('\n');
        }
        page.Append('\n');
    }
